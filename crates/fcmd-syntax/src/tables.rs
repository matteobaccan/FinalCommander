//! What each language looks like.
//!
//! The tables are deliberately small. A highlighter that knows every word of a language is a
//! compiler front end; one that knows how the language writes a comment, a string and a
//! number, plus the words anyone would point at and call keywords, colours real files
//! correctly and fits on a page. Where a language is a near-relative of another — C, C++,
//! Java, C# — the shape is shared and only the word list differs.

use crate::Flavour;

/// One language, as the scanner needs it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Syntax {
    pub name: &'static str,
    /// Matched against the end of the file name, without a dot.
    pub extensions: &'static [&'static str],
    /// Whole names, for the files that carry no extension at all.
    pub filenames: &'static [&'static str],
    pub flavour: Flavour,
    pub line_comment: &'static [&'static str],
    pub block_comment: Option<(&'static str, &'static str)>,
    /// Rust nests block comments; C does not. It decides where a file stops being a comment.
    pub nested_comments: bool,
    /// The characters that open and close a string.
    pub quotes: &'static str,
    pub escape: Option<char>,
    /// Whether an unclosed string carries on to the next line.
    pub multiline_strings: bool,
    /// `#include`, `#define`: a `#` at the start of a line is a directive, not a comment.
    pub preproc: bool,
    pub keywords: &'static [&'static str],
    pub types: &'static [&'static str],
}

/// The syntax for a file name, or `None` when we have nothing to say about it.
pub fn of_name(name: &str) -> Option<&'static Syntax> {
    let lower = name.to_ascii_lowercase();
    let stem = lower.rsplit('/').next().unwrap_or(&lower);
    if let Some(found) = SYNTAXES.iter().find(|s| s.filenames.contains(&stem)) {
        return Some(found);
    }
    let ext = stem.rsplit_once('.').map(|(_, e)| e)?;
    // A dotfile is not an extension: `.gitignore` has no stem before the dot.
    if stem.starts_with('.') && stem.matches('.').count() == 1 {
        return None;
    }
    SYNTAXES.iter().find(|s| s.extensions.contains(&ext))
}

/// The syntax a language's *name* asks for: what a fenced code block's info string says
/// (```` ```rust ````), a `# vim: ft=` line, or a user picking a language from a list.
///
/// The name is matched first, then the extensions, so `rust` and `rs` both arrive at Rust and
/// `c++`, `cpp` and `cc` all arrive at C++.
pub fn of_language(name: &str) -> Option<&'static Syntax> {
    let wanted = name.trim().to_ascii_lowercase();
    if wanted.is_empty() {
        return None;
    }
    if let Some(found) = SYNTAXES
        .iter()
        .find(|s| s.name.to_ascii_lowercase() == wanted)
    {
        return Some(found);
    }
    // The names people write that are not the table's: a fence says `sh` or `bash`, never
    // `shell`, and `md` as often as `markdown`.
    let alias = match wanted.as_str() {
        "bash" | "zsh" | "ksh" | "console" | "shell-session" => "sh",
        "golang" => "go",
        "c++" | "cplusplus" => "cpp",
        "c#" | "csharp" => "cs",
        "js" | "node" | "mjs" => "javascript",
        "ts" => "typescript",
        "py" | "python3" => "python",
        "yml" => "yaml",
        "dockerfile" | "docker" => "dockerfile",
        "makefile" => "make",
        "md" => "markdown",
        other => other,
    };
    if let Some(found) = SYNTAXES
        .iter()
        .find(|s| s.name.to_ascii_lowercase() == alias)
    {
        return Some(found);
    }
    SYNTAXES.iter().find(|s| s.extensions.contains(&alias))
}

